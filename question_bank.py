# ─── 索引（執行時建立，供 matcher 使用） ──────────────────────────
_BY_FRAMEWORK: Dict[str, List[dict]] = {}
_BY_ID: Dict[str, dict] = {}
for _q_item in BANK:
    _BY_ID[_q_item["id"]] = _q_item
    for _fw in _q_item["framework_ids"]:
        _BY_FRAMEWORK.setdefault(_fw, []).append(_q_item)


def get_all() -> List[dict]:
    """回傳整個題庫。"""
    return BANK


def get_by_framework(framework_id: str) -> List[dict]:
    """回傳適用於指定框架的所有問題。"""
    return _BY_FRAMEWORK.get(framework_id, [])


def get_by_id(question_id: str) -> Optional[dict]:
    return _BY_ID.get(question_id)


def stats() -> dict:
    """題庫統計（供啟動時健康檢查與測試使用）。"""
    cats: Dict[str, int] = {}
    fws: Dict[str, int] = {}
    for q in BANK:
        cats[q["category"]] = cats.get(q["category"], 0) + 1
        for fw in q["framework_ids"]:
            fws[fw] = fws.get(fw, 0) + 1
    return {"total": len(BANK), "by_category": cats, "by_framework": fws}
